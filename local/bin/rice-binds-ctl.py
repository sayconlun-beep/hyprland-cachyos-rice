def emit(**payload):
    print(json.dumps(payload, ensure_ascii=False))
    sys.exit(0)


# ----------------------------------------------------------------- parsing --
def strip_comment(line):
    """hyprlang: `#` starts a comment, `##` is a literal `#`."""
    out, i = [], 0
    while i < len(line):
        if line[i] == "#":
            if line[i + 1:i + 2] == "#":
                out.append("#")
                i += 2
                continue
            return "".join(out), line[i + 1:].strip()
        out.append(line[i])
        i += 1
    return "".join(out), ""


def expand(text, variables):
    # Longest name first, so `$bin` can never eat the front of `$binary`.
    for name in sorted(variables, key=len, reverse=True):
        text = text.replace("$" + name, variables[name])
    return text


def read_vars():
    variables = {}
    for path in VAR_FILES:
        try:
            with open(path) as f:
                lines = f.read().splitlines()
        except OSError:
            continue
        for raw in lines:
            body, _ = strip_comment(raw)
            m = VAR.match(body.strip())
            if m:
                variables[m.group(1)] = expand(m.group(2).strip(), variables)
    return variables


def norm_mods(text, strict=False):
    found = set()
    for part in re.split(r"[\s_+]+", text.strip().upper()):
        if not part or part == "NONE":
            continue
        if part not in MOD_ALIASES:
            if strict:
                raise ValueError(f"unknown modifier {part}")
            found.add(part)
            continue
        found.add(MOD_ALIASES[part])
    known = [m for m in MOD_ORDER if m in found]
    return " ".join(known + sorted(found - set(MOD_ORDER)))


def norm_key(text):
    key = text.strip()
    return key.upper() if len(key) == 1 else key


def parse():
    variables = read_vars()
    binds, seen = [], {}
    category, submap = "General", ""
    with open(BASELINE) as f:
        lines = f.read().splitlines()
    for raw in lines:
        m = SECTION.match(raw.strip())
        if m:
            name = m.group(1)
            category = name[:1].upper() + name[1:]
            continue
        body, comment = strip_comment(raw)
        body = body.strip()
        m = SUBMAP.match(body)
        if m:
            submap = "" if m.group(1) == "reset" else m.group(1)
            continue
        m = BIND.match(body)
        if not m or submap:          # submap binds are not the everyday keys
            continue
        kind = m.group(1)
        described = "d" in kind[4:]
        count = 5 if described else 4
        parts = [p.strip() for p in expand(m.group(2), variables).split(",", count - 1)]
        parts += [""] * (count - len(parts))
        if described:
            mods, key, desc, dispatcher, arg = parts
        else:
            (mods, key, dispatcher, arg), desc = parts, ""
        mods = norm_mods(mods)
        bid = f"{kind}|{mods}|{key.lower()}"
        n = seen.get(bid, 0)
        seen[bid] = n + 1
        if n:
            bid += f"#{n}"
        binds.append({
            "id": bid, "category": category, "kind": kind,
            "base_mods": mods, "base_key": key, "desc": desc,
            "dispatcher": dispatcher, "arg": arg, "comment": comment,
        })
    return binds


# ------------------------------------------------------------- presenting --
def action_text(b):
    text = f"{b['dispatcher']} {b['arg']}".strip()
    return re.sub(r"(~|\$HOME|/home/[^/\s]+)/\.local/bin/", "", text)


def label(b):
    if b["desc"]:
        return b["desc"]
    action = action_text(b)
    for pattern, result in LABELS:
        m = re.search(pattern, action)
        if m:
            return result(m) if callable(result) else result
    return b["comment"] or action


def pretty_key(key):
    low = key.lower()
    if low in KEY_NAMES:
        return KEY_NAMES[low]
    if low.startswith("code:"):
        return "key " + key[5:]
    return key.upper() if len(key) == 1 else key


def keys_of(mods, key):
    return [MOD_NAMES.get(m, m.title()) for m in mods.split()] + [pretty_key(key)]


def editable(b):
    # A mouse button or wheel cannot be captured from a keyboard event.
    return b["kind"] != "bindm" and not b["base_key"].lower().startswith("mouse")


# ------------------------------------------------------------------ state --
def load_state():
    try:
        with open(OVERRIDES) as f:
            for line in f:
                if line.startswith("# state: "):
                    return json.loads(line[len("# state: "):])
    except (OSError, ValueError):
        pass
    return {}


def effective(b, state):
    o = state.get(b["id"])
    return (o["mods"], o["key"]) if o else (b["base_mods"], b["base_key"])


def same(a, b):
    return a[0] == b[0] and a[1].lower() == b[1].lower()


def override(state, b, mods, key):
    if same((mods, key), (b["base_mods"], b["base_key"])):
        state.pop(b["id"], None)
    else:
        state[b["id"]] = {"mods": mods, "key": key}


def bind_value(b, mods, key):
    fields = [mods, key] + ([b["desc"]] if "d" in b["kind"][4:] else []) + [b["dispatcher"], b["arg"]]
    return ", ".join(fields).replace("#", "##")


def write_overrides(binds, state):
    by = {b["id"]: b for b in binds}
    live = {i: o for i, o in state.items() if i in by}
    out = [HEADER, "# state: " + json.dumps(live, sort_keys=True, ensure_ascii=False), ""]
    for i in live:
        out.append(f"unbind = {by[i]['base_mods']}, {by[i]['base_key']}")
    if live:
        out.append("")
    for i, o in live.items():
        out.append(f"{by[i]['kind']} = {bind_value(by[i], o['mods'], o['key'])}")
    os.makedirs(os.path.dirname(OVERRIDES), exist_ok=True)
    tmp = OVERRIDES + ".tmp"
    with open(tmp, "w") as f:
        f.write("\n".join(out) + "\n")
    os.replace(tmp, OVERRIDES)


def hypr_keyword(name, value):
    try:
        r = subprocess.run([HYPRCTL, "keyword", name, value],
                           capture_output=True, text=True, timeout=5)
    except (OSError, subprocess.TimeoutExpired) as e:
        return str(e)
    out = r.stdout.strip()
    if r.returncode == 0 and out in ("ok", ""):
        return None
    return f"{name} {value}: {out or r.stderr.strip() or 'hyprctl failed'}"


def apply_live(by, old, new, ids):
    # Every unbind before any bind: in a swap, one bind's new keys are the
    # other's old ones, and binding first would be unbound straight after.
    errors = []
    for i in ids:
        m, k = effective(by[i], old)
        errors.append(hypr_keyword("unbind", f"{m},{k}"))
    for i in ids:
        m, k = effective(by[i], new)
        errors.append(hypr_keyword(by[i]["kind"], bind_value(by[i], m, k)))
    return [e for e in errors if e]


# --------------------------------------------------------------- commands --
def cmd_list(_args):
    binds, state = parse(), load_state()
    out = []
    for b in binds:
        m, k = effective(b, state)
        out.append({
            "id": b["id"], "category": b["category"], "label": label(b),
            "action": action_text(b), "kind": b["kind"], "mods": m, "key": k,
            "keys": keys_of(m, k), "base_keys": keys_of(b["base_mods"], b["base_key"]),
            "overridden": b["id"] in state, "editable": editable(b),
        })
    emit(ok=True, binds=out)


def cmd_set(args):
    binds = parse()
    by = {b["id"]: b for b in binds}
    b = by.get(args.id)
    if not b:
        emit(ok=False, error=f"no bind with id {args.id}")
    if not editable(b):
        emit(ok=False, error="mouse and scroll binds can only be changed in binds.conf")
    try:
        mods = norm_mods(args.mods, strict=True)
    except ValueError as e:
        emit(ok=False, error=str(e))
    key = norm_key(args.key)
    if not key:
        emit(ok=False, error="no key given")

    old = load_state()
    new = {i: dict(o) for i, o in old.items()}
    here = effective(b, old)
    if same(here, (mods, key)):
        emit(ok=True, message=f"{label(b)} is already {' + '.join(keys_of(mods, key))}")

    clash = [o for o in binds if o["id"] != b["id"] and same(effective(o, old), (mods, key))]
    if clash and not args.swap:
        c = clash[0]
        emit(ok=False, conflict={"id": c["id"], "label": label(c), "keys": keys_of(mods, key)})

    override(new, b, mods, key)
    ids = [b["id"]]
    for c in clash:
        override(new, c, *here)
        ids.append(c["id"])
    write_overrides(binds, new)
    warnings = apply_live(by, old, new, ids)

    message = f"{label(b)} → {' + '.join(keys_of(mods, key))}"
    if clash:
        message += f", {label(clash[0])} → {' + '.join(keys_of(*here))}"
    emit(ok=True, message=message, warnings=warnings)


def cmd_reset(args):
    binds = parse()
    by = {b["id"]: b for b in binds}
    old = load_state()
    ids = [i for i in ([args.id] if args.id else list(old)) if i in old and i in by]
    if not ids:
        emit(ok=True, message="Nothing to reset")

    # Anything sitting on a reset bind's committed keys - the other half of a
    # swap - has to go back too, or the reset would create a clash.
    new = {i: o for i, o in old.items() if i not in ids}
    grew = True
    while grew:
        grew = False
        for i in list(new):
            if i in by and any(same(effective(by[i], new), (by[r]["base_mods"], by[r]["base_key"])) for r in ids):
                ids.append(i)
                del new[i]
                grew = True

    write_overrides(binds, new)
    warnings = apply_live(by, old, new, ids)
    if len(ids) == 1:
        b = by[ids[0]]
        message = f"{label(b)} back to {' + '.join(keys_of(b['base_mods'], b['base_key']))}"
    else:
        message = f"{len(ids)} binds back to binds.conf"
    emit(ok=True, message=message, warnings=warnings)


def cmd_reapply(_args):
    binds = parse()
    by = {b["id"]: b for b in binds}
    state = {i: o for i, o in load_state().items() if i in by}
    base = {}
    warnings = apply_live(by, base, state, list(state))
    emit(ok=True, message=f"{len(state)} overrides reapplied", warnings=warnings)


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__.strip().splitlines()[0])
    sub = ap.add_subparsers(dest="cmd", required=True)
    sub.add_parser("list").set_defaults(fn=cmd_list)
    s = sub.add_parser("set")
    s.add_argument("id")
    s.add_argument("mods", help='e.g. "SUPER SHIFT", or "" for none')
    s.add_argument("key")
    s.add_argument("--swap", action="store_true")
    s.set_defaults(fn=cmd_set)
    r = sub.add_parser("reset")
    r.add_argument("id", nargs="?")
    r.set_defaults(fn=cmd_reset)
    sub.add_parser("reapply").set_defaults(fn=cmd_reapply)
    args = ap.parse_args(argv)
    try:
        args.fn(args)
    except OSError as e:
        emit(ok=False, error=str(e))


if __name__ == "__main__":
    main()
