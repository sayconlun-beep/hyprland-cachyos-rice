#!/usr/bin/env python3
"""
Hyprland appearance control - the engine behind `rice-settings look`.

Sibling of rice-monitor-ctl.py and deliberately the same shape: read the
committed config, apply live with `hyprctl keyword`, persist to a generated
file in conf.d that is sourced after the baseline. hyprland.conf is never
rewritten.

  rice-look-ctl.py list                        JSON: every exposed option
  rice-look-ctl.py set decoration:rounding 10  apply live AND persist
  rice-look-ctl.py set general:gaps_in 6 --no-save   live only, for drag preview
  rice-look-ctl.py reset [path]                drop one override, or all
  rice-look-ctl.py reapply                     push saved overrides back

Only the paths in SCHEMA below are ever read or written. That matters for one
in particular: `general:col.active_border` is owned by the palette - matugen
re-derives it from the wallpaper and rice-theme-reload pushes it live. It is
deliberately absent here - a setting that wrote a border colour would be
overwritten by the next wallpaper change, and would look like this tool had failed.

Values are resolved from the config FILES, not from `hyprctl getoption`.
getoption returns every type key populated at once (int, float, str, data), so
reading it correctly means knowing each option's type anyway, and this tool
edits config - showing what the config says keeps the two coherent. The
consequence worth knowing: a value changed by hand with `hyprctl keyword`
since the last reload is live but not shown here.
"""

import argparse
import json
import os
import re
import shutil
import subprocess
import sys

HYPRCTL = os.environ.get("RICE_HYPRCTL", "hyprctl")
CONF_DIR = os.path.expanduser(os.environ.get("RICE_HYPR_DIR", "~/.config/hypr"))
OVERRIDES = os.path.join(CONF_DIR, "conf.d", "20-look.conf")
BASELINE = os.path.join(CONF_DIR, "hyprland.conf")

HEADER = """# Generated by rice-look-ctl.py - do not hand-edit.
#
# Sourced from conf.d after the baseline, so these values win. Delete this
# file and reload to fall back to the committed look; `rice-look-ctl.py reset`
# does the same without touching the file by hand.
"""

# path, label, type, and the bounds rice-settings shows. `group` only decides
# which heading it appears under.
SCHEMA = [
    ("general:gaps_in",  "Inner gaps",   "int",   0, 40, 1,    "Layout"),
    ("general:gaps_out", "Outer gaps",   "int",   0, 60, 1,    "Layout"),
    ("general:border_size", "Border",    "int",   0, 10, 1,    "Layout"),

    ("decoration:rounding", "Rounding",  "int",   0, 24, 1,    "Windows"),
    ("decoration:active_opacity",   "Active opacity",   "float", 0.5, 1.0, 0.01, "Windows"),
    ("decoration:inactive_opacity", "Inactive opacity", "float", 0.5, 1.0, 0.01, "Windows"),

    ("decoration:blur:enabled", "Blur",       "bool",  0, 1, 1, "Blur"),
    ("decoration:blur:size",    "Blur size",  "int",   1, 20, 1, "Blur"),
    ("decoration:blur:passes",  "Blur passes", "int",  1, 5, 1,  "Blur"),
    ("decoration:blur:brightness", "Blur brightness", "float", 0.5, 1.5, 0.05, "Blur"),
    ("decoration:blur:xray",    "Blur xray",  "bool",  0, 1, 1,  "Blur"),

    ("decoration:shadow:enabled", "Shadow",       "bool", 0, 1, 1, "Shadow"),
    ("decoration:shadow:range",   "Shadow range", "int",  0, 60, 1, "Shadow"),

    ("animations:enabled", "Animations", "bool", 0, 1, 1, "Motion"),
]
BY_PATH = {row[0]: row for row in SCHEMA}


def die(msg, code=1):
    print(msg, file=sys.stderr)
    sys.exit(code)


def parse_config(path):
    """Flatten a Hyprland config to {dotted:path: value}.

    Blocks nest (`decoration { blur { size = 5 } }` -> decoration:blur:size).
    Later assignments win, matching how Hyprland itself reads a config. Keys
    outside SCHEMA are collected too and simply never looked up, so bind and
    windowrule lines are harmless noise rather than something to special-case.
    """
    values = {}
    stack = []
    try:
        with open(path) as fh:
            lines = fh.read().splitlines()
    except OSError:
        return values
    for raw in lines:
        line = raw.split("#", 1)[0].strip()
        if not line:
            continue
        if line == "}":
            if stack:
                stack.pop()
            continue
        m = re.match(r"^([A-Za-z_][\w\-]*)\s*\{$", line)
        if m:
            stack.append(m.group(1))
            continue
        if "=" in line:
            key, _, val = line.partition("=")
            key, val = key.strip(), val.strip()
            if key and stack:
                values[":".join(stack + [key])] = val
        # Anything else (a stray brace, a continuation) is ignored rather than
        # guessed at - this only needs to read the handful of keys in SCHEMA.
    return values


def coerce(kind, text):
    """Config text -> a JSON-friendly value, or None when unusable."""
    if text is None:
        return None
    t = str(text).strip()
    if kind == "bool":
        if t.lower() in ("true", "yes", "on", "1"):
            return True
        if t.lower() in ("false", "no", "off", "0"):
            return False
        return None
    try:
        return int(t) if kind == "int" else float(t)
    except ValueError:
        # An option set to a variable ($gaps) or an expression is real config,
        # just not something a slider can represent.
        return None


def render_value(kind, value):
    if kind == "bool":
        return "true" if value else "false"
    if kind == "int":
        return str(int(round(float(value))))
    return ("%g" % float(value))


def resolve():
    """Every schema option with its effective value and where it came from."""
    over = parse_config(OVERRIDES)
    base = parse_config(BASELINE)
    out = []
    for path, label, kind, lo, hi, step, group in SCHEMA:
        value, source = None, "unset"
        if path in over:
            value, source = coerce(kind, over[path]), "override"
        if value is None and path in base:
            value, source = coerce(kind, base[path]), "baseline"
        if value is None:
            source = "unset"
        out.append({
            "path": path, "label": label, "type": kind, "group": group,
            "min": lo, "max": hi, "step": step,
            "value": value, "source": source,
            "baseline": coerce(kind, base.get(path)),
        })
    return out


def load_overrides():
    stored = parse_config(OVERRIDES)
    return {p: v for p, v in stored.items() if p in BY_PATH}


def write_overrides(values):
    """values: {dotted:path: rendered string}. Rebuilt as nested blocks."""
    tree = {}
    for path, val in values.items():
        parts = path.split(":")
        node = tree
        for part in parts[:-1]:
            node = node.setdefault(part, {})
        node[parts[-1]] = val

    def emit(node, depth):
        pad = "    " * depth
        text = ""
        for key in sorted(node):
            val = node[key]
            if isinstance(val, dict):
                text += f"{pad}{key} {{\n" + emit(val, depth + 1) + f"{pad}}}\n"
            else:
                text += f"{pad}{key} = {val}\n"
        return text

    body = HEADER + "\n" + emit(tree, 0)
    os.makedirs(os.path.dirname(OVERRIDES), exist_ok=True)
    tmp = OVERRIDES + ".tmp"
    with open(tmp, "w") as fh:
        fh.write(body)
    os.replace(tmp, OVERRIDES)


def apply_live(path, rendered):
    if shutil.which(HYPRCTL) is None and not os.path.exists(HYPRCTL):
        return False, "hyprctl not found"
    try:
        res = subprocess.run([HYPRCTL, "keyword", path, rendered],
                             capture_output=True, text=True, timeout=5)
    except (OSError, subprocess.SubprocessError) as exc:
        return False, str(exc)
    text = (res.stdout or "") + (res.stderr or "")
    ok = res.returncode == 0 and "invalid" not in text.lower()
    return ok, text.strip()


def cmd_list(_args):
    print(json.dumps({"options": resolve()}, indent=2))
    return 0


def cmd_set(args):
    row = BY_PATH.get(args.path)
    if row is None:
        die("unknown option %r - have:\n  %s"
            % (args.path, "\n  ".join(p for p, *_ in SCHEMA)), 2)
    _, _, kind, lo, hi, _step, _group = row
    value = coerce(kind, args.value)
    if value is None:
        die("%r is not a %s" % (args.value, kind), 2)
    if kind != "bool" and not (lo <= value <= hi):
        die("%s must be between %g and %g (got %g)" % (args.path, lo, hi, value), 2)
    rendered = render_value(kind, value)

    result = {"path": args.path, "value": rendered}
    if not args.no_apply:
        ok, detail = apply_live(args.path, rendered)
        result["applied"] = ok
        result["detail"] = detail
        if not ok:
            # Same rule as the monitor engine: never persist something the
            # compositor just refused.
            result["saved"] = False
            print(json.dumps(result, indent=2))
            return 1
    if not args.no_save:
        stored = load_overrides()
        stored[args.path] = rendered
        write_overrides(stored)
        result["saved"] = True
        result["file"] = OVERRIDES
    print(json.dumps(result, indent=2))
    return 0


def cmd_reset(args):
    stored = load_overrides()
    if args.path:
        if args.path not in BY_PATH:
            die("unknown option %r" % args.path, 2)
        if args.path not in stored:
            print(json.dumps({"path": args.path, "removed": False}, indent=2))
            return 0
        del stored[args.path]
        write_overrides(stored)
        targets = [args.path]
    else:
        targets = list(stored)
        stored = {}
        write_overrides(stored)

    # Push the baseline value back so reset takes effect without a reload.
    base = parse_config(BASELINE)
    restored = []
    for path in targets:
        if path in base:
            kind = BY_PATH[path][2]
            value = coerce(kind, base[path])
            if value is not None:
                ok, _ = apply_live(path, render_value(kind, value))
                restored.append({"path": path, "reapplied": ok})
    print(json.dumps({"removed": targets, "restored": restored}, indent=2))
    return 0


def cmd_reapply(_args):
    done = []
    for path, rendered in sorted(load_overrides().items()):
        ok, detail = apply_live(path, rendered)
        done.append({"path": path, "applied": ok, "detail": detail})
    print(json.dumps({"reapplied": done}, indent=2))
    return 0 if all(d["applied"] for d in done) else 1


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__.strip().splitlines()[0])
    sub = ap.add_subparsers(dest="cmd", required=True)

    sub.add_parser("list").set_defaults(fn=cmd_list)

    s = sub.add_parser("set")
    s.add_argument("path")
    s.add_argument("value")
    s.add_argument("--no-apply", action="store_true")
    s.add_argument("--no-save", action="store_true",
                   help="live only - what a slider drag uses until it is released")
    s.set_defaults(fn=cmd_set)

    r = sub.add_parser("reset")
    r.add_argument("path", nargs="?")
    r.set_defaults(fn=cmd_reset)

    sub.add_parser("reapply").set_defaults(fn=cmd_reapply)

    args = ap.parse_args(argv)
    return args.fn(args)


if __name__ == "__main__":
    sys.exit(main())
