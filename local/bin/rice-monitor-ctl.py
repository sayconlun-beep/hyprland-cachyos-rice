#!/usr/bin/env python3
"""
Monitor control for the rice - the engine behind `rice-settings displays`.

Monitor layout, scale, refresh and VRR are otherwise only editable by opening
hyprland.conf. This does the actual work; rice-settings is only a rofi UI over
it. Keeping the logic here means it is testable, scriptable from a terminal,
and outlives whichever front-end is in fashion - it already survived its first
one, a Noctalia plugin.

  rice-monitor-ctl.py list                    JSON: every output, live + configured
  rice-monitor-ctl.py set DP-2 --vrr 2        apply live AND persist
  rice-monitor-ctl.py set DP-2 --scale 1.25 --no-save    live only, dies on reload
  rice-monitor-ctl.py reset DP-2              drop the override for one output
  rice-monitor-ctl.py reapply                 push every saved override back

Two layers, deliberately:

  hyprland.conf              the committed baseline, hand-edited, in git.
  conf.d/10-monitors.conf    generated overrides, sourced after the baseline
                             so they win, and gitignored like colors.conf.

Nothing here rewrites hyprland.conf. A bad setting is undone with `reset`, or
by deleting the generated file and reloading - the baseline is never damaged.
"""

import argparse
import json
import os
import re
import shutil
import subprocess
import sys

HYPRCTL = os.environ.get("RICE_HYPRCTL", "hyprctl")
CONF_DIR = os.path.expanduser(os.environ.get("RICE_HYPR_DIR", "~/.config/hypr"))
OVERRIDES = os.path.join(CONF_DIR, "conf.d", "10-monitors.conf")
BASELINE = os.path.join(CONF_DIR, "hyprland.conf")

HEADER = """# Generated by rice-monitor-ctl.py - do not hand-edit.
#
# Lives in conf.d, which hyprland.conf sources at the very end, so these
# lines override the baseline monitor rules. Delete this file and reload to
# fall back to the committed layout; `rice-monitor-ctl.py reset <output>`
# drops a single output.
"""

# A monitor rule's trailing extras are keyword/value pairs: `, vrr, 2`.
# Only the ones this tool manages are parsed and rewritten; anything else on an
# existing line is preserved verbatim so a hand-added `bitdepth, 10` survives.
MANAGED_EXTRAS = ("vrr", "transform")

# A disabled output's rule is just `NAME, disable` - Hyprland's syntax has
# nowhere to carry the mode, position and scale. Without somewhere to put them,
# disabling a monitor and re-enabling it silently reset it to preferred/auto/1.
# They are parked in an inline comment (Hyprland treats # as a comment
# anywhere, and read_rules strips it) and restored on re-enable.
KEEP_MARK = "rice-keep:"


def die(msg, code=1):
    print(msg, file=sys.stderr)
    sys.exit(code)


def hyprctl_json(*args):
    if shutil.which(HYPRCTL) is None and not os.path.exists(HYPRCTL):
        die("hyprctl not found - is Hyprland running?", 3)
    try:
        out = subprocess.run([HYPRCTL, "-j", *args], capture_output=True,
                             text=True, timeout=5)
    except (OSError, subprocess.SubprocessError) as exc:
        die(f"hyprctl failed: {exc}", 3)
    if out.returncode != 0:
        die(f"hyprctl {' '.join(args)} failed: {out.stderr.strip()}", 3)
    try:
        return json.loads(out.stdout)
    except ValueError as exc:
        die(f"hyprctl returned unparseable JSON: {exc}", 3)


def parse_mode(text):
    """'2560x1440@165.00Hz' -> (2560, 1440, 165.0). None if unrecognised."""
    # The Hz suffix is optional as a UNIT, not as a stray "z": hyprctl prints
    # "2560x1440@165.00Hz" but a user types "2560x1440@180", and `Hz?` would
    # have required the H and rejected the second form outright.
    m = re.match(r"^\s*(\d+)x(\d+)(?:@\s*([\d.]+)\s*(?:Hz)?)?\s*$", text, re.I)
    if not m:
        return None
    return int(m.group(1)), int(m.group(2)), float(m.group(3) or 0) or None


def fmt_refresh(hz):
    """Hyprland matches modes loosely, but keep the precision it reports."""
    if hz is None:
        return ""
    return f"{hz:.5f}".rstrip("0").rstrip(".")


def read_rules(path):
    """Parse `monitor = ...` lines out of a config file, in order.

    Returns a list of (connector, rule_body, raw_line). Commented lines and
    the catch-all `monitor = , preferred...` rule are skipped: the catch-all
    has no connector to key an override on.
    """
    rules = []
    try:
        with open(path) as fh:
            lines = fh.read().splitlines()
    except OSError:
        return rules
    for raw in lines:
        line = raw.split("#", 1)[0].strip()
        m = re.match(r"^monitor\s*=\s*(.+)$", line)
        if not m:
            continue
        body = m.group(1)
        connector = body.split(",", 1)[0].strip()
        if not connector:
            continue
        rules.append((connector, body, raw))
    return rules


def rule_to_settings(body, raw=None):
    """Split a monitor rule body into the fields this tool understands.

    `raw` is the original line, which for a disabled output carries the
    parked settings in a trailing rice-keep comment.
    """
    parts = [p.strip() for p in body.split(",")]
    out = {"connector": parts[0] if parts else ""}
    if len(parts) > 1 and parts[1]:
        if parts[1].lower() == "disable":
            out["disabled"] = True
        else:
            out["mode"] = parts[1]
    if len(parts) > 2 and parts[2]:
        out["position"] = parts[2]
    if len(parts) > 3 and parts[3]:
        out["scale"] = parts[3]
    # Trailing keyword/value pairs.
    extras = parts[4:]
    keep = []
    i = 0
    while i < len(extras) - 1:
        key, val = extras[i].lower(), extras[i + 1]
        if key in MANAGED_EXTRAS:
            out[key] = val
        else:
            keep.extend([extras[i], extras[i + 1]])
        i += 2
    if i < len(extras) and extras[i]:
        keep.append(extras[i])          # a dangling token - preserve it
    out["_extra"] = keep
    if out.get("disabled") and raw and KEEP_MARK in raw:
        parked = raw.split(KEEP_MARK, 1)[1].strip()
        restored = rule_to_settings(out["connector"] + ", " + parked)
        restored["disabled"] = True
        return restored
    return out


def settings_to_rule(s):
    if s.get("disabled"):
        return f"{s['connector']}, disable"
    parts = [s["connector"],
             s.get("mode") or "preferred",
             s.get("position") or "auto",
             str(s.get("scale") or 1)]
    for key in MANAGED_EXTRAS:
        if s.get(key) not in (None, ""):
            parts.extend([key, str(s[key])])
    parts.extend(s.get("_extra") or [])
    return ", ".join(parts)


def live_outputs():
    """Every output hyprctl knows about, enabled or not."""
    mons = hyprctl_json("monitors", "all")
    outs = {}
    for m in mons:
        name = m.get("name") or ""
        if not name:
            continue
        modes = []
        for text in m.get("availableModes") or []:
            p = parse_mode(text)
            if p:
                modes.append({"width": p[0], "height": p[1], "refresh": p[2]})
        # Deduplicate on (w,h,refresh) but keep hyprctl's ordering, which puts
        # the preferred mode first.
        seen, uniq = set(), []
        for mo in modes:
            key = (mo["width"], mo["height"], round(mo["refresh"] or 0, 2))
            if key not in seen:
                seen.add(key)
                uniq.append(mo)
        outs[name] = {
            "connector": name,
            "description": m.get("description") or "",
            "make": m.get("make") or "",
            "model": m.get("model") or "",
            "disabled": bool(m.get("disabled")),
            "focused": bool(m.get("focused")),
            "live": {
                "width": m.get("width"),
                "height": m.get("height"),
                "refresh": m.get("refreshRate"),
                "scale": m.get("scale"),
                "x": m.get("x"),
                "y": m.get("y"),
                "transform": m.get("transform"),
                # hyprctl reports whether VRR is ACTIVE right now, not which
                # mode is configured - mode 2 on a windowed desktop reads
                # false. So the configured value comes from the config files,
                # never from here.
                "vrr_active": bool(m.get("vrr")),
            },
            "modes": uniq,
        }
    return outs


def configured(connector):
    """Effective config for one output: override wins, else baseline, else {}."""
    for path in (OVERRIDES, BASELINE):
        found = None
        for conn, body, raw in read_rules(path):
            if conn == connector:
                found = (body, raw)  # last rule for this output wins
        if found is not None:
            return rule_to_settings(found[0], found[1])
    return {"connector": connector, "_extra": []}


def cmd_list(_args):
    outs = live_outputs()
    overridden = {c for c, _, _ in read_rules(OVERRIDES)}
    for name, o in outs.items():
        cfg = configured(name)
        cfg.pop("_extra", None)
        o["configured"] = cfg
        o["overridden"] = name in overridden
    print(json.dumps({"outputs": [outs[k] for k in sorted(outs)]}, indent=2))
    return 0


def render_line(s):
    """One `monitor = ...` line, parking a disabled output's other fields."""
    if not s.get("disabled"):
        return "monitor = " + settings_to_rule(s)
    enabled = dict(s)
    enabled["disabled"] = False
    rest = settings_to_rule(enabled)
    _, _, rest = rest.partition(", ")
    line = "monitor = %s, disable" % s["connector"]
    if rest:
        line += "  # %s %s" % (KEEP_MARK, rest)
    return line


def write_overrides(rules):
    """rules: dict connector -> settings. Written sorted, atomically."""
    body = HEADER + "\n"
    for conn in sorted(rules):
        body += render_line(rules[conn]) + "\n"
    os.makedirs(os.path.dirname(OVERRIDES), exist_ok=True)
    tmp = OVERRIDES + ".tmp"
    with open(tmp, "w") as fh:
        fh.write(body)
    os.replace(tmp, OVERRIDES)


def load_overrides():
    out = {}
    for conn, rule_body, raw in read_rules(OVERRIDES):
        out[conn] = rule_to_settings(rule_body, raw)
    return out


def apply_live(settings):
    rule = settings_to_rule(settings)
    try:
        res = subprocess.run([HYPRCTL, "keyword", "monitor", rule],
                             capture_output=True, text=True, timeout=5)
    except (OSError, subprocess.SubprocessError) as exc:
        return False, str(exc)
    ok = res.returncode == 0 and "invalid" not in (res.stdout or "").lower()
    return ok, (res.stdout or res.stderr or "").strip()


def cmd_set(args):
    outs = live_outputs()
    if args.connector not in outs:
        die("unknown output %r - have: %s"
            % (args.connector, ", ".join(sorted(outs)) or "none"), 2)
    out = outs[args.connector]
    cfg = configured(args.connector)
    cfg["connector"] = args.connector

    if args.mode is not None:
        parsed = parse_mode(args.mode)
        if parsed is None:
            die(f"unparseable mode {args.mode!r} - want WIDTHxHEIGHT[@Hz]", 2)
        w, h, hz = parsed
        if not args.force:
            # Compare on rounded Hz: hyprctl reports 179.88 where a user types
            # 180, and refusing that would be useless pedantry.
            have = {(m["width"], m["height"], round(m["refresh"] or 0))
                    for m in out["modes"]}
            if out["modes"] and (w, h, round(hz or 0)) not in have:
                die("%s cannot do %s. Available: %s\n(use --force to set it anyway)"
                    % (args.connector, args.mode,
                       ", ".join(sorted({"%dx%d@%s" % (m["width"], m["height"],
                                                       fmt_refresh(m["refresh"]))
                                         for m in out["modes"]}))), 2)
        cfg["mode"] = "%dx%d@%s" % (w, h, fmt_refresh(hz)) if hz else "%dx%d" % (w, h)

    if args.scale is not None:
        if args.scale <= 0:
            die("scale must be positive", 2)
        # Hyprland rejects a scale that does not land on whole logical pixels.
        # Catch it here with a clear message instead of letting the compositor
        # silently refuse the rule.
        width = out["live"]["width"]
        if width and not args.force:
            logical = width / args.scale
            if abs(logical - round(logical)) > 0.001:
                die("scale %s gives %s logical px on a %dpx-wide panel, which "
                    "Hyprland rejects - it needs a whole number.\nTry %s "
                    "(= %d px), or --force."
                    % (args.scale, round(logical, 3), width,
                       round(width / round(logical), 6), round(logical)), 2)
        cfg["scale"] = ("%g" % args.scale)

    if args.position is not None:
        if args.position != "auto" and not re.match(r"^-?\d+x-?\d+$", args.position):
            die("position must be XxY (e.g. 2560x0) or 'auto'", 2)
        cfg["position"] = args.position

    if args.vrr is not None:
        if args.vrr not in (0, 1, 2, 3):
            die("vrr must be 0 (off), 1 (on), 2 (fullscreen) or 3 (fs+game)", 2)
        cfg["vrr"] = args.vrr

    if args.transform is not None:
        if not 0 <= args.transform <= 7:
            die("transform must be 0-7", 2)
        cfg["transform"] = args.transform

    if args.disabled is not None:
        cfg["disabled"] = args.disabled
        if not args.disabled:
            cfg.pop("disabled", None)

    result = {"connector": args.connector, "rule": settings_to_rule(cfg)}

    if not args.no_apply:
        ok, detail = apply_live(cfg)
        result["applied"] = ok
        result["detail"] = detail
        if not ok:
            # Do NOT persist a rule the compositor just refused - that would
            # bake the breakage in across reloads.
            result["saved"] = False
            print(json.dumps(result, indent=2))
            return 1

    if not args.no_save:
        rules = load_overrides()
        rules[args.connector] = cfg
        write_overrides(rules)
        result["saved"] = True
        result["file"] = OVERRIDES
    print(json.dumps(result, indent=2))
    return 0


def cmd_reset(args):
    rules = load_overrides()
    if args.connector not in rules:
        print(json.dumps({"connector": args.connector, "removed": False,
                          "detail": "no override was set"}, indent=2))
        return 0
    del rules[args.connector]
    write_overrides(rules)
    # Put the baseline rule back live, so reset takes effect without a reload.
    base = None
    for conn, body, raw in read_rules(BASELINE):
        if conn == args.connector:
            base = (body, raw)
    applied = None
    if base is not None:
        applied, _ = apply_live(rule_to_settings(base[0], base[1]))
    print(json.dumps({"connector": args.connector, "removed": True,
                      "reapplied_baseline": applied}, indent=2))
    return 0


def cmd_reapply(_args):
    rules = load_overrides()
    done = []
    for conn in sorted(rules):
        ok, detail = apply_live(rules[conn])
        done.append({"connector": conn, "applied": ok, "detail": detail})
    print(json.dumps({"reapplied": done}, indent=2))
    return 0 if all(d["applied"] for d in done) else 1


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__.strip().splitlines()[0])
    sub = ap.add_subparsers(dest="cmd", required=True)

    sub.add_parser("list", help="JSON dump of every output").set_defaults(fn=cmd_list)

    s = sub.add_parser("set", help="change one output")
    s.add_argument("connector")
    s.add_argument("--mode", help="WIDTHxHEIGHT[@Hz]")
    s.add_argument("--scale", type=float)
    s.add_argument("--position", help="XxY or 'auto'")
    s.add_argument("--vrr", type=int, help="0 off, 1 on, 2 fullscreen, 3 fs+game")
    s.add_argument("--transform", type=int, help="0-7")
    s.add_argument("--disabled", type=lambda v: v.lower() in ("1", "true", "yes"),
                   help="true/false")
    s.add_argument("--no-apply", action="store_true", help="write only, no live change")
    s.add_argument("--no-save", action="store_true", help="live only, lost on reload")
    s.add_argument("--force", action="store_true", help="skip mode/scale validation")
    s.set_defaults(fn=cmd_set)

    r = sub.add_parser("reset", help="drop one output's override")
    r.add_argument("connector")
    r.set_defaults(fn=cmd_reset)

    sub.add_parser("reapply", help="push saved overrides back to Hyprland") \
        .set_defaults(fn=cmd_reapply)

    args = ap.parse_args(argv)
    return args.fn(args)


if __name__ == "__main__":
    sys.exit(main())
